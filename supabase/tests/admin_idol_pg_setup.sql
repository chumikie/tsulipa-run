-- Fresh PostgreSQL only. Every UUID, nick and score is invented.
create schema if not exists auth;
create or replace function auth.uid() returns uuid language sql stable as $$
  select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid
$$;
do $$ begin
  if not exists (select 1 from pg_roles where rolname='anon') then create role anon nologin; end if;
  if not exists (select 1 from pg_roles where rolname='authenticated') then create role authenticated nologin; end if;
end $$;
grant usage on schema public, auth to authenticated;

create table public.players(
  id uuid primary key, nick text not null, avatar jsonb, nuvem_visual jsonb,
  visuais text[], nuvem_ms bigint, updated_at timestamptz not null default now()
);
create table public.admins(user_id uuid primary key);
create table public.leaderboard(id bigint generated by default as identity primary key, user_id uuid, "char" text, score integer);
create table public.admin_log(id bigint generated by default as identity primary key, admin uuid, acao text, alvo text, valor text, motivo text);
create function public.eh_admin() returns boolean language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.admins a where a.user_id = auth.uid())
$$;

