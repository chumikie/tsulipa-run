-- UUIDs e saldos inventados.
create schema if not exists auth;
create schema if not exists private;
create or replace function auth.uid() returns uuid language sql stable as $$
  select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid
$$;
do $$ begin
  if not exists (select 1 from pg_roles where rolname = 'anon') then create role anon nologin; end if;
  if not exists (select 1 from pg_roles where rolname = 'authenticated') then create role authenticated nologin; end if;
end $$;
grant usage on schema public, auth to anon, authenticated;

create table public.players(
  id uuid primary key, nick text not null, stars integer not null default 0, best integer not null default 0,
  bloqueado boolean not null default false, updated_at timestamptz not null default now()
);
create table public.star_log(
  id bigint generated by default as identity primary key, user_id uuid not null references public.players(id),
  delta integer not null, reason text not null, created_at timestamptz not null default now()
);
create table public.leaderboard(
  id bigint generated by default as identity primary key, name text, score integer, stars integer,
  "char" text, device_id text, user_id uuid
);
alter table public.leaderboard enable row level security;
create policy "ler ranking" on public.leaderboard for select to anon using (true);
create policy "ler ranking logado" on public.leaderboard for select to authenticated using (true);
grant select, insert, update, delete on public.leaderboard, public.players, public.star_log to anon, authenticated;

