-- Fresh PostgreSQL container only. All UUIDs and balances are invented.
create schema auth;
create function auth.uid() returns uuid language sql stable as $$
  select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid
$$;
create role anon nologin;
create role authenticated nologin;
create role service_role nologin;

create table public.players(
  id uuid primary key,nick text not null,stars integer not null default 0,
  best integer not null default 0,bloqueado boolean not null default false,
  updated_at timestamptz not null default now()
);
create table public.runs(
  id uuid primary key,user_id uuid not null references public.players(id),
  started_at timestamptz not null default now(),
  finished_at timestamptz,score integer,"char" text
);
create table public.star_log(
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.players(id),
  delta integer not null,reason text not null,created_at timestamptz not null default now()
);
create table public.leaderboard(
  id bigint generated by default as identity primary key,
  name text,score integer,stars integer,"char" text,device_id text,user_id uuid
);

-- Pre-existing signature and ACL before CREATE OR REPLACE, mirroring production.
create function public.terminar_corrida(uuid,integer,integer,text,text)
returns json language sql security definer set search_path to 'public'
as $$ select '{"ok":false}'::json $$;
revoke all on function public.terminar_corrida(uuid,integer,integer,text,text) from public;
grant execute on function public.terminar_corrida(uuid,integer,integer,text,text) to authenticated,service_role;

